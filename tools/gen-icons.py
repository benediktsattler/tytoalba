"""Generate src/05-icons.css from Lucide SVG files.

usage: python3 tools/gen-icons.py <lucide-svg-dir> <out-css>
"""
import re
import sys
from pathlib import Path
from urllib.parse import quote

# token name -> lucide icon name
ICONS = {
    "terminal": "square-terminal",
    "upload": "upload",
    "download": "download",
    "plus": "plus",
    "table": "table",
    "eye": "eye",
    "database": "database",
    "menu": "menu",
    "arrow-up": "arrow-up",
    "arrow-down": "arrow-down",
    "trash": "trash-2",
    "move": "move",
    "pencil": "pencil",
    "info": "info",
    "search": "search",
    "sort-desc": "arrow-down-wide-narrow",
    "sort-asc": "arrow-up-narrow-wide",
    "sort": "arrow-up-down",
    "columns": "columns-3",
    "partition": "layout-grid",
    "history": "history",
    "globe": "globe",
    "power": "power",
}

# For elements that can't carry a pseudo-element (e.g. <select>): plain
# background images with a baked-in color instead of masks.
# token name -> (lucide icon name, stroke color)
IMAGES = {
    "ellipsis": ("ellipsis", "#7b7b85"),  # ≈ --sb-muted
}


def minify(svg: str, color: str = "#000") -> str:
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    # only on the <svg> tag itself — <rect> needs its own width/height
    svg = re.sub(
        r"<svg[^>]*>",
        lambda m: re.sub(r'\s(class|width|height)="[^"]*"', "", m.group(0)),
        svg,
        count=1,
    )
    svg = svg.replace("currentColor", color)
    svg = re.sub(r"\s+", " ", svg).replace("> <", "><").replace(" />", "/>")
    svg = svg.replace(" >", ">").strip()
    return svg.replace('"', "'")


def data_uri(svg: str) -> str:
    return "data:image/svg+xml," + quote(svg, safe=" '/=:;,.-")


def main() -> None:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    lines = [
        "/* ========== Icons (Lucide, ISC license — https://lucide.dev) ==========",
        "   Generated from lucide-static SVGs, used as CSS masks: an element sets",
        "   `--icon: var(--i-<name>)` and gets the shape, the color comes from",
        "   `background-color` (currentColor by default), so every icon follows",
        "   the color tokens. To add one: add it to ICONS in tools/gen-icons.py",
        "   and re-run it (see README). --img-* tokens are",
        "   fixed-color background images for elements without pseudo-elements.",
        "   GENERATED by tools/gen-icons.py — don't edit by hand. */",
        "",
        ":root {",
    ]
    for token, name in ICONS.items():
        svg = minify((src / f"{name}.svg").read_text())
        lines.append(f'   --i-{token}: url("{data_uri(svg)}");')
    for token, (name, color) in IMAGES.items():
        svg = minify((src / f"{name}.svg").read_text(), color)
        lines.append(f'   --img-{token}: url("{data_uri(svg)}");')
    lines.append("}")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
